// After `next build` (postbuild): allows each page's own inline scripts by
// their SHA-256 hashes, so no page's Content-Security-Policy needs
// 'unsafe-inline' for scripts. Node built-ins only.
//
// Next.js inlines a few scripts in every page (its bootstrap and the
// server-rendered payload) and the layout adds one (lib/keep-scenario.ts).
// Their text changes with every build and with the data, so the hashes are
// computed from out/ after each build, never written by hand.
//
// How Cloudflare Pages combines out/_headers
// (developers.cloudflare.com/pages/configuration/headers/):
//   - a request gets the headers of every rule whose pattern matches it;
//   - a header set by more than one matching rule is joined with ", ", which
//     for CSP means two policies, both enforced;
//   - rules apply in file order, and "! Name" removes what earlier rules set.
// So /* keeps the one policy from public/_headers, with the 404 page's
// hashes added (Cloudflare serves 404.html for any unknown path, which only
// /* matches). Each page then gets a rule after /* that detaches that policy
// and sets its own. Every HTML response carries exactly one policy, and none
// allows 'unsafe-inline' scripts. style-src is left as it is.

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const CSP = "Content-Security-Policy";
/** Cloudflare's limits for _headers. */
export const MAX_RULES = 100;
export const MAX_LINE = 2000;

/** The text of every inline <script> (one without a src attribute). */
export function inlineScripts(html: string): string[] {
  return [...html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi)]
    .filter((m) => !/\bsrc\s*=/i.test(m[1]!))
    .map((m) => m[2]!);
}

/** A CSP hash source for a script's exact text, as the browser computes it. */
export function hashSource(script: string): string {
  return `'sha256-${createHash("sha256").update(script, "utf8").digest("base64")}'`;
}

/** The paths a page is served at: its clean URL and its .html form. */
export function routesFor(file: string): string[] {
  const path = "/" + file.split(sep).join("/");
  if (path === "/index.html") return ["/", "/index.html"];
  if (path.endsWith("/index.html")) return [path.slice(0, -10), path];
  return [path.slice(0, -5), path];
}

/**
 * `policy` with `hashes` added to its script-src. Throws if the policy has
 * no script-src or already allows inline scripts some other way.
 */
export function withHashes(policy: string, hashes: string[]): string {
  const directives = policy.split(";").map((d) => d.trim());
  const i = directives.findIndex((d) => /^script-src\s/.test(d));
  if (i < 0) throw new Error("The template policy has no script-src.");
  const sources = directives[i]!.split(/\s+/).slice(1);
  if (sources.some((s) => /^'(unsafe-inline|unsafe-hashes)'$/.test(s)))
    throw new Error("script-src must not allow inline scripts by keyword.");
  const unique = [...new Set(hashes)].sort();
  directives[i] = ["script-src", ...sources, ...unique].join(" ");
  return directives.join("; ");
}

export type Page = { file: string; scripts: string[] };

/**
 * out/_headers: the template with the 404 page's hashes in the /* policy,
 * then one rule per page route with that page's own policy.
 */
export function buildHeaders(template: string, pages: Page[]): string {
  const lines = template.split("\n");
  const cspLines = lines
    .map((line, i) => ({ line, i }))
    .filter(({ line }) => line.trimStart().startsWith(`${CSP}:`));
  if (cspLines.length !== 1)
    throw new Error(`Expected one ${CSP} line in the template.`);
  const { line, i } = cspLines[0]!;
  const indent = line.slice(0, line.length - line.trimStart().length);
  const policy = line.slice(line.indexOf(":") + 1).trim();
  const hashesOf = (p: Page) => p.scripts.map(hashSource);

  const notFound = pages.find((p) => p.file === "404.html");
  if (!notFound) throw new Error("out/404.html is missing.");
  lines[i] = `${indent}${CSP}: ${withHashes(policy, hashesOf(notFound))}`;

  const out = [
    lines.join("\n").trimEnd(),
    "",
    "# Generated by scripts/csp-hashes.ts after the build: each page's own",
    "# policy, with the hashes of its inline scripts. Each rule comes after /*,",
    "# so its detach (!) removes the /* policy before setting this one.",
  ];
  for (const page of [...pages].sort((a, b) => a.file.localeCompare(b.file)))
    for (const route of routesFor(page.file))
      out.push(
        "",
        route,
        `${indent}! ${CSP}`,
        `${indent}${CSP}: ${withHashes(policy, hashesOf(page))}`,
      );
  const text = out.join("\n") + "\n";

  const rules = text
    .split("\n")
    .filter((l) => /^\S/.test(l) && !l.startsWith("#"));
  if (rules.length > MAX_RULES)
    throw new Error(`${rules.length} rules; Cloudflare allows ${MAX_RULES}.`);
  const long = text.split("\n").find((l) => l.length > MAX_LINE);
  if (long)
    throw new Error(
      `A line is ${long.length} characters; the limit is ${MAX_LINE}.`,
    );
  return text;
}

/** Every .html file under out/, outside _next. */
export function htmlFiles(root: string): string[] {
  return readdirSync(root, { recursive: true, withFileTypes: true })
    .filter((e) => e.isFile() && e.name.endsWith(".html"))
    .map((e) => relative(root, join(e.parentPath, e.name)))
    .filter((f) => !f.startsWith(`_next${sep}`))
    .sort();
}

if (import.meta.main) {
  const OUT = join(import.meta.dirname, "..", "out");
  const pages = htmlFiles(OUT).map((file) => ({
    file,
    scripts: inlineScripts(readFileSync(join(OUT, file), "utf8")),
  }));
  const headers = join(OUT, "_headers");
  writeFileSync(headers, buildHeaders(readFileSync(headers, "utf8"), pages));
  console.log(
    `csp-hashes: ${pages
      .map((p) => `${p.file} ${new Set(p.scripts.map(hashSource)).size}`)
      .join(", ")} inline script hash(es) in out/_headers`,
  );
}
